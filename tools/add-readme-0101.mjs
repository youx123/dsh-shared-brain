#!/usr/bin/env node
/** README：加 0.10.1 小节 + 把安装命令的版本号跟上 */
import { readFileSync, writeFileSync } from 'node:fs'

const P = 'C:/Users/13176/Documents/dsh-shared-brain-patches/README.md'
const src = readFileSync(P, 'utf8')

const ANCHOR = '## 0.10.0 更新说明'
if (src.split(ANCHOR).length - 1 !== 1) throw new Error('锚点不唯一')

const SECTION = `## 0.10.1 更新说明

0.10.0 之后做了一轮三路专项审计（安全 / 情感与自主意识 / 性能），查出 30 处问题，全修了。
逐条细节见 [FIXES.md](FIXES.md) 的「补充 19」。

### 会真泄露 / 真失效的四条

- **磁盘上的明文凭据终于被擦掉了**：以前脱敏只擦内存 —— \`readStore()\` 的写回判断看的是「擦掉了几条」，可规整函数早就先擦过一遍，所以永远是 0，磁盘上那份从来没更新过。跨机同步的写入又是裸写、不过脱敏，从远端拉下来的脏条目会再推上去。
- **记忆条目不再能被当成指令**：召回原文直接拼进提示词，一条写着自己闭合标签的记忆就能逃出包装、伪造系统标记。现在注入话术整段过滤、标签转义，注入正文也做了 HTML 转义。
- **心情终于能影响说话了**：「心情变了 3 点才算显著」而判定提示词让模型只给 −1~−3 —— 模型越听话越永远过不去闸门，心情播报恒为空。现在看原始幅度。
- **表情提示不再被心情闸门陪葬**：原来心情没变化就直接返回空，表情那一段一次都没跑过。

### 别再往云上推的东西

- **本机路径 / 会话 id 不上云**：以前 127 条记忆里 75 条带着绝对路径（含系统用户名）同步上去了
- **「会话 → 人设」绑定只留本机**：合并结果不再带 \`bySession\`
- **选中会话的自动互动设置不再被同步清空**：本地和推送用两套不同的规整

### 删了的东西真的会消失

模块条目和自定义人设的删除**从来没传播过** —— 删除检测把待删列表同时当成「现有条目」和「上次见过」，交集全中，恒返回空。
真实同步记录里 26 条墓碑全是记忆条目，模块和人设一条都没有。修的时候同时补了「第一次同步不判删除」的守卫，不然新机器一连上就会把远端清空。

### 情感记忆接上了行为

\`intimacy\` / \`sentiment\` / \`target\` 以前只影响召回排序，对行为没有任何影响 —— 「记住老大讨厌啰嗦」和「记住老大讨厌啰嗦但亲密度 0.9」效果完全一样。
现在对老大的负向情感累积到一定程度会把心情判低，主动搭话改用更 soft 的调子。

### 测试

新增 \`tests/audit-0101.test.mjs\`（35 条），每条对应一个审计里实测复现过的现象。更新了 2 条「测的是旧 bug」的断言。

---

`

let out = src.replace(ANCHOR, SECTION + ANCHOR)
out = out.replace('pnpm add file:vendor/dsh-shared-brain-0.10.0.tgz', 'pnpm add file:vendor/dsh-shared-brain-0.10.1.tgz')

writeFileSync(P, out, 'utf8')
console.log('[ok] README 已加 0.10.1 小节')
